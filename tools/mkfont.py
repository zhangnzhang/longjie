import sys
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont
src,out=sys.argv[1],sys.argv[2]
f=TTFont(src); f.flavor=None; f.save('/tmp/ps2p.ttf')
font=ImageFont.truetype('/tmp/ps2p.ttf',8)
rows=[]
for c in range(32,127):
    im=Image.new('L',(8,8),0); ImageDraw.Draw(im).text((0,0),chr(c),font=font,fill=255)
    rows.append(''.join('%02x'%sum((1<<(7-x)) for x in range(8) if im.getpixel((x,y))>127) for y in range(8)))
open(out,'w').write('// 8x8 bitmap font baked from Press Start 2P (OFL 1.1). Generated by tools/mkfont.py\nexport const FONT="'+''.join(rows)+'";\n')
